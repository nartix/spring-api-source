package com.ferozfaiz.uniapi.category.infrastructure.persistence.jdbc;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.lang.Nullable;

final class DescriptorBackedAdminCategoryJdbcFixture {

  static final String SYSTEM_A = "descriptor-a";
  static final String SYSTEM_B = "descriptor-b";
  static final String TABLE_A = "test_category_a";
  static final String TABLE_B = "test_category_b";
  static final String CLOSURE_A = "test_category_a_closure";
  static final String CLOSURE_B = "test_category_b_closure";

  private DescriptorBackedAdminCategoryJdbcFixture() {}

  static void createSchema(JdbcTemplate jdbc) {
    createCategoryTable(jdbc, TABLE_A);
    createClosureTable(jdbc, CLOSURE_A);
    createCategoryTable(jdbc, TABLE_B);
    createClosureTable(jdbc, CLOSURE_B);
  }

  static void dropSchema(JdbcTemplate jdbc) {
    jdbc.execute("DROP TABLE IF EXISTS " + CLOSURE_A);
    jdbc.execute("DROP TABLE IF EXISTS " + CLOSURE_B);
    jdbc.execute("DROP TABLE IF EXISTS " + TABLE_A);
    jdbc.execute("DROP TABLE IF EXISTS " + TABLE_B);
  }

  static Long insertNode(
    JdbcTemplate jdbc,
    String tableName,
    String name,
    String slug,
    @Nullable Long parentId,
    boolean active,
    long sortRank
  ) {
    return jdbc.queryForObject(
      """
      INSERT INTO %s (parent_id, sort_rank, name, slug, active)
      VALUES (?, ?, ?, ?, ?)
      RETURNING id
      """.formatted(tableName),
      Long.class,
      parentId,
      sortRank,
      name,
      slug,
      active
    );
  }

  static void insertClosure(
    JdbcTemplate jdbc,
    String tableName,
    Long ancestorId,
    Long descendantId,
    int depth
  ) {
    jdbc.update(
      "INSERT INTO " + tableName + " (ancestor_id, descendant_id, depth) VALUES (?, ?, ?)",
      ancestorId,
      descendantId,
      depth
    );
  }

  private static void createCategoryTable(JdbcTemplate jdbc, String tableName) {
    jdbc.execute(
      """
      CREATE TABLE IF NOT EXISTS %s (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        parent_id BIGINT NULL,
        sort_rank BIGINT NOT NULL DEFAULT 1000000000,
        name TEXT NOT NULL,
        slug TEXT NOT NULL,
        active BOOLEAN NOT NULL DEFAULT TRUE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (slug)
      )
      """.formatted(tableName)
    );
  }

  private static void createClosureTable(JdbcTemplate jdbc, String tableName) {
    jdbc.execute(
      """
      CREATE TABLE IF NOT EXISTS %s (
        ancestor_id BIGINT NOT NULL,
        descendant_id BIGINT NOT NULL,
        depth INTEGER NOT NULL,
        PRIMARY KEY (ancestor_id, descendant_id)
      )
      """.formatted(tableName)
    );
  }
}
